"""Ports: the interface of every component boundary.

Rule (Dependency Inversion): high-level code depends ONLY on these Protocols. Concrete classes
implement them. Only `tsdb.bootstrap` (the composition root) chooses implementations, so swapping
one (e.g. skip list -> red-black tree, Bloom -> cuckoo filter, JSON MANIFEST -> binary) is a new
class + one line in bootstrap. Nothing else changes.

This module imports only `tsdb.model`, so it can never create an import cycle.

    Port                 Default implementation              Possible swap
    -------------------  ----------------------------------  -------------------------------
    OrderedStore         memtable.skiplist.SkipList          red-black tree, AVL tree
    MembershipFilter(+F) sstable.bloom.BloomFilter           cuckoo / xor filter
    TableFactory/R/W     sstable.factory.SSTableFactory      another file format version
    ManifestPort         storage.manifest.ManifestStore      binary manifest, log-structured
    WalPort              wal.wal.Wal                         replicated WAL, N WALs (design-qa #54)
    ShardRouter          engine.routing.SingleShardRouter    consistent hashing
    PostingSource        catalog.inverted_index              roaring bitmaps
    SeriesResolver       catalog.series_catalog              —
    CompactionPolicy     compaction.policy.TimeWindowPolicy  leveled, plain size-tiered
    Aggregator(+registry) query.aggregate                     new functions (p99, last, ...)
    FileOps              storage.fileio.OsFileOps            failing fsync (tests), mmap
    FaultInjector        faults.NoFaults / EnvFaults         —
    TimeSeriesStore      engine.database.Database            fake (API tests)
"""

from __future__ import annotations

from collections.abc import Iterable, Iterator
from pathlib import Path
from typing import Protocol, runtime_checkable

from tsdb.model import (Aggregation, ManifestState, Point, Seq, SeriesId, SeriesKey, TimeWindow,
                        Timestamp, Tombstone)

# ============================================================================ side effects
@runtime_checkable
class FileOps(Protocol):
    def open_append(self, path: Path) -> int: ...
    def append(self, fd: int, data: bytes) -> None: ...
    def fsync(self, fd: int) -> None: ...
    def fsync_dir(self, path: Path) -> None: ...
    def close(self, fd: int) -> None: ...
    def read_all(self, path: Path) -> bytes: ...
    def read_range(self, path: Path, offset: int, length: int) -> bytes: ...
    def size(self, path: Path) -> int: ...
    def atomic_replace(self, path: Path, data: bytes) -> None: ...
    def publish_tmp(self, tmp_path: Path, final_path: Path) -> None: ...
    def truncate(self, path: Path, length: int) -> None: ...
    def remove(self, path: Path) -> None: ...
    def list_dir(self, path: Path) -> list[Path]: ...
    def make_dirs(self, path: Path) -> None: ...


@runtime_checkable
class FaultInjector(Protocol):
    def hit(self, point: str) -> None: ...


# ============================================================================ memtable
OrderedKey = tuple[int, int, int]      # (series_id, timestamp, -seq)


@runtime_checkable
class OrderedStore(Protocol):
    """Sorted map from OrderedKey to value, for the memtable.
    Contract: unique keys; iteration in ascending key order; readers may iterate while ONE
    writer inserts (no lock on the read side)."""

    def insert(self, key: OrderedKey, value: float) -> None: ...
    def iter_from(self, key: OrderedKey) -> Iterator[tuple[OrderedKey, float]]: ...
    def __iter__(self) -> Iterator[tuple[OrderedKey, float]]: ...
    def __len__(self) -> int: ...


@runtime_checkable
class MemtablePort(Protocol):
    """A memtable as seen by WAL writers (apply), readers (read_*), and flush (iter_for_flush)."""

    max_seq: Seq
    max_timestamp: Timestamp       # newest data time seen (window closing)
    min_timestamp: Timestamp | None  # oldest point time (None = no points): flush when its window closes

    def apply(self, entries: list[Point | Tombstone]) -> None: ...
    def freeze(self) -> None: ...
    def is_full(self) -> bool: ...
    def read_series(self, series_id: SeriesId, from_ts: Timestamp, to_ts: Timestamp,
                    snapshot_seq: Seq) -> Iterator[Point]: ...
    def tombstones_for(self, series_id: SeriesId, snapshot_seq: Seq) -> list[Tombstone]: ...
    def iter_for_flush(self) -> Iterator[Point]: ...
    def all_tombstones(self) -> list[Tombstone]: ...


@runtime_checkable
class MemtableFactory(Protocol):
    def __call__(self) -> MemtablePort: ...


# ============================================================================ sstable
@runtime_checkable
class MembershipFilter(Protocol):
    """'Is series X in this file?' -> False = surely not, True = maybe."""

    def add(self, series_id: SeriesId) -> None: ...
    def may_contain(self, series_id: SeriesId) -> bool: ...
    def to_bytes(self) -> bytes: ...


@runtime_checkable
class MembershipFilterFactory(Protocol):
    def new(self, expected_items: int, false_positive_rate: float) -> MembershipFilter: ...
    def load(self, data: bytes) -> MembershipFilter: ...


@runtime_checkable
class TableCursor(Protocol):
    """Per-query, forward-only reader over one table: series must be requested in ascending id
    order; implementations may reuse the last block for neighbour series."""

    def read_series(self, series_id: SeriesId, from_ts: Timestamp, to_ts: Timestamp) -> Iterator[Point]: ...
    @property
    def blocks_read(self) -> int: ...


@runtime_checkable
class TableReader(Protocol):
    @property
    def name(self) -> str: ...
    @property
    def window(self) -> TimeWindow: ...
    @property
    def min_ts(self) -> Timestamp: ...
    @property
    def max_ts(self) -> Timestamp: ...
    @property
    def size_bytes(self) -> int: ...
    def may_contain(self, series_id: SeriesId, from_ts: Timestamp, to_ts: Timestamp) -> bool: ...
    def tombstones_for(self, series_id: SeriesId) -> list[Tombstone]: ...
    def cursor(self) -> TableCursor: ...
    def iter_all(self) -> Iterator[Point]: ...
    def all_tombstones(self) -> list[Tombstone]: ...
    def close(self) -> None: ...


@runtime_checkable
class TableWriter(Protocol):
    def add(self, point: Point) -> None: ...
    def add_tombstone(self, tombstone: Tombstone) -> None: ...
    def finish(self) -> Path: ...          # fsynced .tmp path
    def abort(self) -> None: ...


@runtime_checkable
class TableFactory(Protocol):
    def new_writer(self, window: TimeWindow, file_no: int) -> TableWriter: ...
    def publish(self, tmp_path: Path, window: TimeWindow, file_no: int) -> Path: ...
    def open_reader(self, path: Path, window: TimeWindow) -> TableReader: ...


# ============================================================================ durability
@runtime_checkable
class ManifestPort(Protocol):
    def load(self) -> ManifestState | None: ...
    def commit(self, state: ManifestState) -> None: ...


@runtime_checkable
class WalPort(Protocol):
    """The write-ahead log as seen by the shard."""

    def write(self, puts: list[tuple[SeriesId, Timestamp, float]]) -> None: ...
    def delete(self, series_ids: list[SeriesId], from_ts: Timestamp, to_ts: Timestamp) -> None: ...
    def rotate(self, new_segment_no: int, new_memtable: MemtablePort) -> Path: ...
    def close(self) -> None: ...


@runtime_checkable
class ShardRouter(Protocol):
    def route(self, key: SeriesKey) -> int: ...
    def all_shards(self) -> range: ...


# ============================================================================ catalog / index
@runtime_checkable
class PostingSource(Protocol):
    def add(self, series_id: SeriesId, key: SeriesKey) -> None: ...
    def postings(self, tag_key: str, tag_value: str) -> frozenset[SeriesId]: ...
    def metric_universe(self, metric: str | None) -> frozenset[SeriesId]: ...
    def size_of(self, tag_key: str, tag_value: str) -> int: ...


@runtime_checkable
class SeriesResolver(Protocol):
    def load(self) -> None: ...
    def get_or_create(self, key: SeriesKey) -> tuple[SeriesId, bool]: ...
    def key_of(self, series_id: SeriesId) -> SeriesKey: ...
    def sync(self) -> None: ...


# ============================================================================ query
@runtime_checkable
class Aggregator(Protocol):
    def add(self, value: float) -> None: ...
    def result(self) -> float: ...


@runtime_checkable
class AggregatorFactory(Protocol):
    def __call__(self) -> Aggregator: ...


# ============================================================================ API boundary
@runtime_checkable
class TimeSeriesStore(Protocol):
    def write(self, points: Iterable[tuple[SeriesKey, Timestamp, float]]) -> int: ...
    def query(self, metric: str, filter_text: str | None, from_ts: Timestamp, to_ts: Timestamp,
              agg: Aggregation | None, bucket_ms: int | None) -> object: ...
    def list_series(self, metric: str | None, filter_text: str | None) -> object: ...
    def delete(self, metric: str | None, filter_text: str | None, from_ts: Timestamp,
               to_ts: Timestamp) -> int: ...
    def close(self) -> None: ...
